#!/usr/bin/env python3
"""
kimodo_replay.py — Replay a Kimodo G1 qpos CSV on the physical robot via LLSdk.

Loads a MuJoCo qpos CSV generated by Kimodo's G1Skeleton34 and replays it
frame-by-frame through LLSdk (rt/lowcmd).  Before any command is sent, the
full joint-target table and safety analysis are displayed, and confirmation
is required.

Safety analysis cross-checks every frame against two constraints from ll_sdk:
  1. Ramp speed  — ll_sdk._ramp_publish defaults to 0.35 rad/s at 50 Hz.
                   If a frame delta would require more ramp time than the
                   frame interval allows, the motion will run slower than
                   generated (RAMP>FRAME).  We send with ramp_speed=0 to
                   honour the frame rate, so large deltas arrive instantly —
                   flagged as INSTANT UNSAFE when |Δq|/Δt > 1.5 rad/s.
  2. Joint limits — from ll_sdk._LEG_LIMITS, arm_fk.JOINT_LIMITS, and
                    low_level_commands.py waist limits.

Usage
-----
    python kimodo_replay.py motion.csv [options]

Options
-------
    --fps FPS       Playback frame rate (default 30)
    --root-dof N    Columns to skip at the start of each CSV row for the
                    root pose.  7 = free joint (3 pos + 4 quat), the MuJoCo
                    default for a humanoid; 0 = joint angles only (default 7)
    --iface IFACE   Network interface (default eth0)
    --domain ID     DDS domain ID — 0 = real robot, 1 = sim (default 0)
    --dry-run       Analyse every frame without connecting to the robot
    --no-color      Disable ANSI colour output

Confirmation prompt (per-frame unless errors are present, which always stop)
----------------------------------------------------------------------------
    y / Enter   Send this frame
    s           Skip this frame (do not update prev_targets)
    a           Send all remaining frames without per-frame confirmation
    q           Quit
"""
from __future__ import annotations

import argparse
import os
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np

